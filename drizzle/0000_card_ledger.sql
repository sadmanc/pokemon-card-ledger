CREATE TABLE IF NOT EXISTS items (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id text NOT NULL,
  name text NOT NULL,
  item_type text NOT NULL DEFAULT 'card',
  set_name text NOT NULL DEFAULT '',
  card_number text NOT NULL DEFAULT '',
  condition text NOT NULL DEFAULT 'Near Mint',
  grade text NOT NULL DEFAULT 'Raw',
  quantity integer NOT NULL DEFAULT 0,
  cost_basis_cad double precision NOT NULL DEFAULT 0,
  current_value_cad double precision NOT NULL DEFAULT 0,
  valuation_date text NOT NULL DEFAULT '',
  valuation_source text NOT NULL DEFAULT 'PriceCharting',
  source_url text NOT NULL DEFAULT '',
  notes text NOT NULL DEFAULT '',
  created_at text NOT NULL DEFAULT CURRENT_TIMESTAMP::text,
  updated_at text NOT NULL DEFAULT CURRENT_TIMESTAMP::text
);

CREATE TABLE IF NOT EXISTS transactions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id text NOT NULL,
  kind text NOT NULL,
  transaction_date text NOT NULL,
  item_id integer,
  item_name text NOT NULL DEFAULT '',
  quantity integer NOT NULL DEFAULT 0,
  amount_cad double precision NOT NULL DEFAULT 0,
  cash_delta_cad double precision NOT NULL DEFAULT 0,
  credit_delta_cad double precision NOT NULL DEFAULT 0,
  fees_cad double precision NOT NULL DEFAULT 0,
  shipping_cad double precision NOT NULL DEFAULT 0,
  tax_cad double precision NOT NULL DEFAULT 0,
  acquisition_cost_cad double precision NOT NULL DEFAULT 0,
  realized_profit_cad double precision NOT NULL DEFAULT 0,
  source text NOT NULL DEFAULT 'Manual',
  notes text NOT NULL DEFAULT '',
  created_at text NOT NULL DEFAULT CURRENT_TIMESTAMP::text,
  updated_at text NOT NULL DEFAULT CURRENT_TIMESTAMP::text
);

CREATE TABLE IF NOT EXISTS trades (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id text NOT NULL,
  trade_date text NOT NULL,
  given_items text NOT NULL DEFAULT '',
  received_items text NOT NULL DEFAULT '',
  value_given_cad double precision NOT NULL DEFAULT 0,
  value_received_cad double precision NOT NULL DEFAULT 0,
  cash_delta_cad double precision NOT NULL DEFAULT 0,
  notes text NOT NULL DEFAULT '',
  created_at text NOT NULL DEFAULT CURRENT_TIMESTAMP::text,
  updated_at text NOT NULL DEFAULT CURRENT_TIMESTAMP::text
);

CREATE TABLE IF NOT EXISTS transaction_items (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id text NOT NULL,
  transaction_id integer NOT NULL,
  item_id integer,
  item_name text NOT NULL,
  item_type text NOT NULL DEFAULT 'card',
  set_name text NOT NULL DEFAULT '',
  card_number text NOT NULL DEFAULT '',
  condition text NOT NULL DEFAULT 'Near Mint',
  grade text NOT NULL DEFAULT 'Raw',
  quantity integer NOT NULL DEFAULT 1,
  amount_cad double precision NOT NULL DEFAULT 0,
  acquisition_cost_cad double precision NOT NULL DEFAULT 0,
  current_value_cad double precision NOT NULL DEFAULT 0,
  valuation_date text NOT NULL DEFAULT '',
  valuation_source text NOT NULL DEFAULT 'PriceCharting',
  source_url text NOT NULL DEFAULT '',
  notes text NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS trade_items (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id text NOT NULL,
  trade_id integer NOT NULL,
  side text NOT NULL,
  item_id integer,
  item_name text NOT NULL,
  item_type text NOT NULL DEFAULT 'card',
  set_name text NOT NULL DEFAULT '',
  card_number text NOT NULL DEFAULT '',
  condition text NOT NULL DEFAULT 'Near Mint',
  grade text NOT NULL DEFAULT 'Raw',
  quantity integer NOT NULL DEFAULT 1,
  value_cad double precision NOT NULL DEFAULT 0,
  current_value_cad double precision NOT NULL DEFAULT 0,
  valuation_date text NOT NULL DEFAULT '',
  valuation_source text NOT NULL DEFAULT 'PriceCharting',
  source_url text NOT NULL DEFAULT '',
  notes text NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS price_observations (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id text NOT NULL,
  item_id integer NOT NULL,
  observed_date text NOT NULL,
  value_cad double precision NOT NULL,
  source text NOT NULL DEFAULT 'PriceCharting',
  source_url text NOT NULL DEFAULT '',
  is_override boolean NOT NULL DEFAULT false
);

CREATE TABLE IF NOT EXISTS snapshots (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id text NOT NULL,
  snapshot_date text NOT NULL,
  holdings_value_cad double precision NOT NULL DEFAULT 0,
  cash_reserve_cad double precision NOT NULL DEFAULT 0,
  credit_reserve_cad double precision NOT NULL DEFAULT 0,
  total_value_cad double precision NOT NULL DEFAULT 0,
  realized_profit_cad double precision NOT NULL DEFAULT 0,
  cumulative_contributions_cad double precision NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS items_owner_updated_idx ON items (owner_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS transactions_owner_date_idx ON transactions (owner_id, transaction_date DESC);
CREATE INDEX IF NOT EXISTS trades_owner_date_idx ON trades (owner_id, trade_date DESC);
CREATE INDEX IF NOT EXISTS transaction_items_owner_transaction_idx ON transaction_items (owner_id, transaction_id);
CREATE INDEX IF NOT EXISTS trade_items_owner_trade_idx ON trade_items (owner_id, trade_id);
CREATE INDEX IF NOT EXISTS observations_owner_date_idx ON price_observations (owner_id, observed_date);
CREATE INDEX IF NOT EXISTS snapshots_owner_date_idx ON snapshots (owner_id, snapshot_date);
